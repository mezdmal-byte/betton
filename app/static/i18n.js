let currentLang = "ru";

function localeTag() {
  if (currentLang === "zh") return "zh-CN";
  if (currentLang === "en") return "en-US";
  return "ru-RU";
}

function t(key, vars) {
  const dict = I18N[currentLang] || I18N.en;
  let text = (dict && dict[key]) || (I18N.en && I18N.en[key]) || (I18N.ru && I18N.ru[key]) || key;
  if (vars) {
    Object.keys(vars).forEach((name) => {
      text = text.split("{" + name + "}").join(String(vars[name]));
    });
  }
  return text;
}

function tt(key, fallback, vars) {
  if (typeof t === "function") {
    const value = t(key, vars);
    if (value && value !== key) return value;
  }
  let text = fallback == null ? key : fallback;
  if (vars) {
    Object.keys(vars).forEach((name) => {
      text = String(text).split("{" + name + "}").join(String(vars[name]));
    });
  }
  return text;
}

function detectLang(code) {
  try {
    const saved = localStorage.getItem("betton-lang");
    if (saved === "ru" || saved === "en" || saved === "zh") return saved;
  } catch (e) { /* private mode */ }
  const raw = String(code || "").toLowerCase();
  if (raw.indexOf("ru") === 0) return "ru";
  if (raw.indexOf("zh") === 0) return "zh";
  if (raw) return "en";
  return "en";
}

function telegramLangCode() {
  try {
    const user = window.Telegram && window.Telegram.WebApp && window.Telegram.WebApp.initDataUnsafe && window.Telegram.WebApp.initDataUnsafe.user;
    if (user && user.language_code) return user.language_code;
  } catch (e) { /* no telegram */ }
  try {
    return navigator.language || "";
  } catch (e2) {
    return "";
  }
}

function applyI18n() {
  const htmlLang = currentLang === "zh" ? "zh-CN" : currentLang;
  if (document.documentElement) document.documentElement.lang = htmlLang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (!key) return;
    el.textContent = t(key);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key) el.setAttribute("placeholder", t(key));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (key) el.setAttribute("aria-label", t(key));
  });
  document.querySelectorAll("#lang-switch [data-lang]").forEach((btn) => {
    btn.classList.toggle("on", btn.getAttribute("data-lang") === currentLang);
  });
}

function setLang(lang, persist) {
  currentLang = (lang === "ru" || lang === "en" || lang === "zh") ? lang : "en";
  if (persist !== false) {
    try { localStorage.setItem("betton-lang", currentLang); } catch (e) { /* private mode */ }
  }
  applyI18n();
  if (typeof window !== "undefined" && typeof window.onLangChange === "function") {
    window.onLangChange();
  }
}

if (typeof window !== "undefined") {
  window.I18N = I18N;
  window.t = t;
  window.tt = tt;
  window.setLang = setLang;
  window.detectLang = detectLang;
  window.localeTag = localeTag;
  window.applyI18n = applyI18n;
}
