import { test, expect } from '@playwright/test'
import { resolve } from 'node:path'
const evidence=resolve('../docs/design/ux-reinvention/evidence/directions')
const names=['exchange','folio','pocket']
for(let v=1;v<=3;v++){
 test(`${names[v-1]} complete synthetic core journey`,async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto(`/prototypes/core/?v=${v}`)
  await expect(page.getByText('Синтетический React-прототип · без API')).toBeVisible()
  await page.screenshot({path:resolve(evidence,`${names[v-1]}-01-feed.png`),fullPage:true,animations:'disabled'})
  await page.getByRole('button',{name:/Поезд прибудет вовремя/}).click()
  await expect(page.getByRole('heading',{level:1,name:'Поезд прибудет вовремя?'})).toBeVisible()
  await page.screenshot({path:resolve(evidence,`${names[v-1]}-02-detail.png`),fullPage:true,animations:'disabled'})
  await page.getByRole('button',{name:'Да 1.67×',exact:true}).click()
  await page.getByLabel('Сумма, TON').fill('150')
  await page.screenshot({path:resolve(evidence,`${names[v-1]}-03-trade.png`),fullPage:true,animations:'disabled'})
  await page.getByRole('button',{name:'Проверить заявку'}).click()
  await expect(page.getByText('Ожидаемое исполнение')).toBeVisible()
  await page.screenshot({path:resolve(evidence,`${names[v-1]}-04-review.png`),fullPage:true,animations:'disabled'})
  await page.getByRole('button',{name:'Подтвердить демо-заявку'}).click()
  await expect(page.getByRole('heading',{name:'Частичное исполнение'})).toBeVisible()
  await page.screenshot({path:resolve(evidence,`${names[v-1]}-05-result.png`),fullPage:true,animations:'disabled'})
  await page.getByRole('button',{name:'Открыть портфель'}).click()
  await expect(page.getByRole('heading',{name:'Портфель',exact:true})).toBeVisible()
  await expect(page.getByTestId('demo-available')).toHaveText('880 TON')
  await expect(page.getByRole('button',{name:/Поезд прибудет вовремя/})).toBeVisible()
  await page.screenshot({path:resolve(evidence,`${names[v-1]}-06-portfolio.png`),fullPage:true,animations:'disabled'})
  expect(errors).toEqual([])
 })
 for(const width of [320,360,390,430])for(const theme of ['light','dark']){
  test(`${names[v-1]} ${width} ${theme} no overflow and limit order`,async({page})=>{
   await page.setViewportSize({width,height:844});await page.emulateMedia({reducedMotion:'reduce'})
   await page.goto(`/prototypes/core/?v=${v}&theme=${theme}`)
   expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
   await page.getByRole('button',{name:/Новая выставка/}).click()
   await page.getByRole('button',{name:'Да Нет предложений',exact:true}).click()
   await expect(page.getByRole('button',{name:'Своя цена',exact:true})).toHaveAttribute('aria-pressed','true')
   await page.getByLabel('Сумма, TON').fill('-1')
   await expect(page.getByRole('button',{name:'Проверить заявку'})).toBeDisabled()
   await page.getByLabel('Сумма, TON').fill('10')
   await page.getByRole('button',{name:'Проверить заявку'}).click()
   await expect(page.getByText('Останется в заявке')).toBeVisible()
   await page.getByRole('button',{name:'Подтвердить демо-заявку'}).click()
   await expect(page.getByRole('heading',{name:'Заявка размещена',exact:true})).toBeVisible()
   await page.getByRole('button',{name:'Открыть портфель'}).click()
   await expect(page.getByTestId('demo-position-count')).toHaveText('0')
   await expect(page.getByTestId('demo-order-count')).toHaveText('1')
   await expect(page.getByTestId('demo-available')).toHaveText('990 TON')
   expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  })
 }
}
test('picker is keyboard driven, URL persistent and does not hijack input',async({page})=>{
 await page.goto('/prototypes/core/?v=1')
 await expect(page.locator('.proto-picker[data-ready]')).toBeVisible()
 await page.keyboard.press('3');await expect(page.locator('[data-direction=pocket]')).toBeVisible()
 await page.reload();await expect(page.locator('[data-direction=pocket]')).toBeVisible()
 await page.getByPlaceholder('Найти событие').fill('поезд');await page.keyboard.press('1')
 await expect(page.locator('[data-direction=pocket]')).toBeVisible()
 await expect(page.getByRole('button',{name:/Команда Альфа/})).not.toBeVisible()
})
test('confirmed receipt survives editing a different unsubmitted draft',async({page})=>{
 await page.goto('/prototypes/core/?v=3')
 await page.getByRole('button',{name:/Поезд прибудет вовремя/}).click()
 await page.getByRole('button',{name:'Да 1.67×',exact:true}).click()
 await page.getByLabel('Сумма, TON').fill('150')
 const action=page.getByRole('button',{name:'Проверить заявку'})
 const actionBox=await action.boundingBox();expect(actionBox).not.toBeNull()
 expect(actionBox!.y+actionBox!.height).toBeLessThanOrEqual(844)
 await action.click()
 await expect(page.getByText('Не хуже коэффициента')).toBeVisible()
 await page.getByRole('button',{name:'Подтвердить демо-заявку'}).click()
 await page.getByRole('button',{name:'Открыть портфель'}).click()
 await page.getByRole('button',{name:/Поезд прибудет вовремя/}).click()
 await page.getByRole('button',{name:'Да 1.67×',exact:true}).click()
 await page.getByLabel('Сумма, TON').fill('5')
 await page.getByRole('button',{name:'Закрыть торговую панель'}).click()
 await expect(page.getByRole('button',{name:'Да 1.67×',exact:true})).toBeFocused()
 await page.getByRole('button',{name:'Портфель',exact:true}).click()
 await expect(page.getByTestId('demo-available')).toHaveText('880 TON')
 await expect(page.getByRole('button',{name:/Поезд прибудет вовремя/})).toContainText('120 TON')
})
